import {createHash} from 'node:crypto';
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {dirname, resolve} from 'node:path';
import {posts, articleTemplate} from '../blog-data.mjs';
import {buildReadingPages} from './reading-pages.mjs';
import {postSummaries} from '../blog-summary-model.mjs';

export function buildBlogRuntime(items, template) {
  const files = new Map(), summaries = postSummaries(items);
  const serialize = (article, slug) => {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) throw new Error('Invalid article slug');
    const data = JSON.stringify(article) + '\n';
    const hash = createHash('sha256').update(data).digest('hex').slice(0, 16);
    const path = `assets/posts/${slug}-${hash}.json`;
    files.set(path, data);
    return path;
  };
  for (const summary of summaries) summary.dataSrc = serialize(items.find(post => post.slug === summary.slug), summary.slug);
  const templateSrc = serialize(template, 'article-template');
  files.set('blog-summaries.mjs', `// Generated by scripts/generate-blog-runtime.mjs; edit the source posts.\nexport const posts = ${JSON.stringify(summaries)};\nexport const templateSrc = ${JSON.stringify(templateSrc)};\n`);
  const covers = [...new Set(summaries.flatMap(post => ['fa', 'en'].map(lang => post.cover[lang]?.src)).filter(Boolean))].sort();
  files.set('assets/blog/previews/manifest.json', JSON.stringify({width: 768, covers}, null, 2) + '\n');
  return files;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const output = [...buildBlogRuntime(posts, articleTemplate), ...buildReadingPages(posts)];
  for (const [name, content] of output) {
    const path = resolve(root, name);
    if (process.argv.includes('--check')) {
      if (readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== content) throw new Error(`Stale runtime content: ${name}. Run node scripts/generate-blog-runtime.mjs.`);
    } else {
      mkdirSync(dirname(path), {recursive: true});
      writeFileSync(path, content, 'utf8');
    }
  }
  console.log(`Blog runtime ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${postSummaries(posts).length} bilingual articles.`);
}
