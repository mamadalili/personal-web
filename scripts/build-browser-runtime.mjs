import {readFile, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {articleModules} from '../blog-enhancements.mjs';

const root = new URL('../', import.meta.url);
const resolveTool = createRequire(new URL('../react-site/package.json', import.meta.url));

export async function buildBrowserRuntime(check) {
  const {rolldown} = await import(pathToFileURL(resolveTool.resolve('rolldown')).href);
  const widgets = Object.values(articleModules).map(([path]) => path.slice(2).split('?')[0]);
  for (const name of ['blog.mjs', 'blog-list.mjs', 'work-stories.mjs', ...new Set(widgets)]) {
    const input = fileURLToPath(new URL(name, root));
    const build = await rolldown({input, platform:'browser', plugins:[{
      name:'local-versioned-imports',
      resolveId(source, importer) {
        if (importer && source.startsWith('./') && source.includes('?')) {
          return fileURLToPath(new URL(source.split('?')[0],pathToFileURL(importer)));
        }
      }
    }]});
    try {
      const {output} = await build.generate({format:'es',codeSplitting:false,minify:true});
      if (output.length !== 1 || output[0].type !== 'chunk' || output[0].imports.length) {
        throw new Error('Unexpected external dependency in ' + name);
      }
      const url = new URL('runtime-' + name, root);
      const code = '// Generated by scripts/generate-blog-runtime.mjs\n' + output[0].code;
      if (check) {
        if ((await readFile(url,'utf8')).replace(/\r\n/g,'\n') !== code) throw new Error('Stale browser bundle: '+name);
      } else await writeFile(url,code);
    } finally { await build.close(); }
  }
}
